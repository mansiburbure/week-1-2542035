def area_circle():
	print("!...Area of circle...!")
	r=float(input("enter radius:"))
	area=3.14*r*r
	print("area of circle",area)

def area_sq():
	print("!...Area of square...!")
	s=float(input("enter side:"))
	area=s*s
	print("area of square:",area)

